#include <iostream>  // Includes the input/output stream library

using namespace std; // Allows us to use cout and endl without writing std::

int main()              // Main function: program execution starts here
{
    int roll = 101;     // Declares an integer variable 'roll' and assigns it the value 101

    char grade = 'A';   // Declares a character variable 'grade' and assigns it the character 'A'

    float fee = 12500.50; // Declares a floating-point variable 'fee' and assigns it 12500.50

    cout << "Roll No: " << roll << endl;   // Displays the student's roll number

    cout << "Grade: " << grade << endl;   // Displays the student's grade

    cout << "Fee: " << fee << endl;       // Displays the student's fee

    return 0;           // Indicates that the program has executed successfully
}
